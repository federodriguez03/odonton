CREATE OR REPLACE FUNCTION asegurar_administrador_activo()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  cantidad INTEGER;
BEGIN
  -- El lock se conserva hasta el COMMIT y serializa altas, bajas e inactivaciones
  -- concurrentes que podrían dejar al sistema sin administrador.
  PERFORM pg_advisory_xact_lock(20261109, 1);

  SELECT COUNT(DISTINCT u.id)::INTEGER
  INTO cantidad
  FROM usuarios u
  JOIN usuarios_roles ur ON ur.usuario_id = u.id
  JOIN roles r ON r.id = ur.rol_id
  WHERE u.activo = TRUE
    AND r.codigo = 'administrador';

  IF cantidad < 1 THEN
    RAISE EXCEPTION USING
      ERRCODE = '23514',
      MESSAGE = 'Debe existir al menos un administrador activo';
  END IF;

  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_usuarios_roles_administrador_activo
AFTER INSERT OR UPDATE OR DELETE ON usuarios_roles
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION asegurar_administrador_activo();

CREATE CONSTRAINT TRIGGER trg_usuarios_administrador_activo
AFTER UPDATE OR DELETE ON usuarios
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION asegurar_administrador_activo();

